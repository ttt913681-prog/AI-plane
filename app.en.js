const AI_KEY_STORAGE_KEY = 'aiLifePlanner:anthropicApiKey';
const AI_MODEL = 'claude-haiku-4-5';
function getStoredApiKey() { try { return localStorage.getItem(AI_KEY_STORAGE_KEY) || ''; } catch (e) { return ''; } }
function setStoredApiKey(key) {
  try { if (key) localStorage.setItem(AI_KEY_STORAGE_KEY, key); else localStorage.removeItem(AI_KEY_STORAGE_KEY); } catch (e) {}
}
async function getAIRecommendations(formData, cuts) {
  const apiKey = getStoredApiKey();
  if (!apiKey) return null;
  const anonTasks = formData.tasks.map((t) => anonymize(t.title) + ' (' + t.type + ', ' + t.priority + ', ' + t.duration + 'min)');
  const prompt = I18N.buildPrompt(formData, anonTasks, cuts);
  try {
    const res = await fetch('https://api.anthropic.com/v1/messages', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'x-api-key': apiKey,
        'anthropic-version': '2023-06-01',
        'anthropic-dangerous-direct-browser-access': 'true'
      },
      body: JSON.stringify({ model: AI_MODEL, max_tokens: 700, messages: [{ role: 'user', content: prompt }] })
    });
    if (!res.ok) return null;
    const data = await res.json();
    const text = (data.content || []).map((b) => b.text || '').join('');
    const parsed = JSON.parse(text.replace(/```json|```/g, '').trim());
    return parsed && parsed.fitness ? parsed : null;
  } catch (e) {
    console.warn('AI recommendation call failed, using offline fallback instead:', e);
    return null;
  }
}

