function anonymize(text) {
  if (!text) return text;
  let out = String(text);
  I18N.banks.forEach((b) => { out = out.split(b).join('[BANK_TOKEN]'); });
  I18N.anonRules.forEach(([re, tok]) => { out = out.replace(re, tok); });
  out = out.replace(/\b[A-Z][a-z]+\s[A-Z][a-z]+\b/g, '[PERSON_TOKEN]');
  out = out.replace(/[A-Z][A-Za-z]*\s?(Corp\.?|Co\.,?\s?Ltd\.?|Inc\.?|Company)/g, '[ORG_TOKEN]');
  return out;
}

// ---------------- Scheduling engine ----------------
function toMin(t) { const [h, m] = t.split(':').map(Number); return h * 60 + m; }
function fmtTime(m) {
  m = ((m % 1440) + 1440) % 1440;
  return String(Math.floor(m / 60)).padStart(2, '0') + ':' + String(m % 60).padStart(2, '0');
}
function prioRank(t) { return t.priority === 'High' ? 0 : t.priority === 'Medium' ? 1 : 2; }

function computeSchedule(formData) {
  const T = I18N.sched;
  const wake = toMin(formData.wakeTime);
  let sleep = toMin(formData.sleepTime);
  if (sleep <= wake) sleep += 1440;
  const workStart = toMin(formData.workStart);
  let workEnd = toMin(formData.workEnd);
  if (workEnd <= workStart) workEnd += 1440;
  const travelMinutes = Math.max(0, Number(formData.travelMinutes) || 0);

  const blocks = [];
  const cuts = [];
  const push = (s, e, activity, category, tag) => {
    if (e > s) blocks.push({ s, e, time: fmtTime(s) + ' - ' + fmtTime(e), activity, category, tag });
  };
  const fatigueSevere = formData.fatigue >= 7;
  const fatigueFactor = fatigueSevere ? 0.35 : formData.fatigue >= 5 ? 0.6 : 1;

  function fitQueue(queue, cursor, limit, windowLabel) {
    const leftover = [];
    queue.forEach((t) => {
      const avail = limit - cursor;
      if (avail <= 10) { leftover.push(t); return; }
      let dur = t.duration, tag = t.priority + ' Priority', adjusted = false;
      if (dur > avail || fatigueSevere) {
        const scaled = Math.max(10, Math.round(Math.min(avail, dur * fatigueFactor)));
        if (scaled < dur) {
          cuts.push({
            task: t.title,
            original: dur + ' ' + T.min,
            adjusted: scaled + ' ' + T.min + ' ' + T.shortened,
            reason: fatigueSevere ? T.reasonFatigue(formData.fatigue) : T.reasonLimited(windowLabel)
          });
          dur = scaled; adjusted = true; tag = 'Adjusted';
        }
      }
      push(cursor, cursor + dur, t.title + (adjusted ? T.adjSuffix : ''), 'Personal Growth', tag);
      cursor += dur;
    });
    return { cursor, leftover };
  }

  let mCursor = wake;
  push(mCursor, mCursor + 20, T.wake, 'Wellbeing', 'Health'); mCursor += 20;
  push(mCursor, mCursor + 25, T.breakfast, 'Routine', 'Life'); mCursor += 25;

  const morningWindowStart = mCursor;
  const morningWindowEnd = Math.max(mCursor, workStart - travelMinutes);
  const morningCapacity = morningWindowEnd - morningWindowStart;
  const eveningWindowStart = workEnd + travelMinutes;
  const eveningWindowEnd = Math.max(eveningWindowStart, sleep - 40);
  const eveningCapacity = eveningWindowEnd - eveningWindowStart;

  const allTasks = formData.tasks.filter((t) => t.type !== 'Work');
  const morningQueue = [], eveningQueue = [], autoQueue = [];
  allTasks.forEach((t) => {
    if (t.when === 'morning') morningQueue.push(t);
    else if (t.when === 'evening') eveningQueue.push(t);
    else autoQueue.push(t);
  });
  let simM = morningCapacity - morningQueue.reduce((s, t) => s + t.duration, 0);
  let simE = eveningCapacity - eveningQueue.reduce((s, t) => s + t.duration, 0);
  autoQueue.slice().sort((a, b) => prioRank(a) - prioRank(b)).forEach((t) => {
    if (simM >= simE) { morningQueue.push(t); simM -= t.duration; }
    else { eveningQueue.push(t); simE -= t.duration; }
  });
  morningQueue.sort((a, b) => prioRank(a) - prioRank(b));
  eveningQueue.sort((a, b) => prioRank(a) - prioRank(b));

  const morningResult = fitQueue(morningQueue, morningWindowStart, morningWindowEnd, T.morning);
  mCursor = morningResult.cursor;
  if (morningWindowEnd > mCursor) {
    push(mCursor, morningWindowEnd, T.freeMorning, 'Routine', 'Free Time');
    mCursor = morningWindowEnd;
  }
  if (workStart > mCursor) push(mCursor, workStart, T.commuteTo + (travelMinutes ? ' (~' + travelMinutes + ' ' + T.min + ')' : ''), 'Routine', 'Life');

  push(workStart, workEnd, T.work, 'Work', T.untouched);

  let eCursor = workEnd;
  if (eveningWindowStart > eCursor) push(eCursor, eveningWindowStart, T.commuteHome + (travelMinutes ? ' (~' + travelMinutes + ' ' + T.min + ')' : ''), 'Routine', 'Life');
  eCursor = eveningWindowStart;

  const combined = eveningQueue.concat(morningResult.leftover).sort((a, b) => prioRank(a) - prioRank(b));
  const eveningResult = fitQueue(combined, eCursor, eveningWindowEnd, T.evening);
  eCursor = eveningResult.cursor;
  eveningResult.leftover.forEach((t) => {
    cuts.push({ task: t.title, original: t.duration + ' ' + T.min, adjusted: T.skipped, reason: T.skipReason });
  });
  if (eCursor < eveningWindowEnd) {
    push(eCursor, eveningWindowEnd, T.dinner, 'Rest', 'Health');
    eCursor = eveningWindowEnd;
  }
  push(eCursor, sleep, T.detox, 'Sleep Prep', 'Rest');

  blocks.sort((a, b) => a.s - b.s);
  return { blocks, cuts, focusMinutes: workEnd - workStart };
}

