function renderChart(blocks) {
  const totals = {};
  blocks.forEach((b) => { totals[b.category] = (totals[b.category] || 0) + (b.e - b.s); });
  const total = Object.values(totals).reduce((a, c) => a + c, 0) || 1;
  const palette = ['#6366f1', '#22d3ee', '#f59e0b', '#f43f5e', '#10b981', '#a78bfa', '#eab308', '#38bdf8'];
  let acc = 0;
  const stops = [];
  const entries = Object.entries(totals).sort((a, b) => b[1] - a[1]);
  entries.forEach(([cat, val], i) => {
    const pct = (val / total) * 100;
    stops.push(`${palette[i % palette.length]} ${acc}% ${acc + pct}%`);
    acc += pct;
  });
  const legend = entries.map(([cat, val], i) =>
    `<div class="flex items-center gap-2 text-xs text-slate-300"><span class="w-3 h-3 rounded-full inline-block shrink-0" style="background:${palette[i % palette.length]}"></span>${cat} · ${Math.round((val / total) * 100)}% (${Math.round(val)} ${I18N.sched.min})</div>`).join('');
  return `<div class="flex items-center gap-6 flex-wrap">
    <div style="width:110px;height:110px;border-radius:50%;background:conic-gradient(${stops.join(',')});flex-shrink:0;"></div>
    <div class="space-y-1.5">${legend}</div></div>`;
}

