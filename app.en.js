function downloadFile(filename, text, mime) {
  const blob = new Blob([text], { type: (mime || 'text/plain') + ';charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
function downloadSchedule() {
  const T = I18N.ui;
  if (!state.scheduleResult) { alert(T.noSchedule); return; }
  const lines = state.scheduleResult.blocks.map((b) => b.time + '  ' + b.activity + '  [' + b.category + ']');
  const cuts = state.scheduleResult.cuts;
  const text = T.txtTitle + '\n' + '='.repeat(40) + '\n\n' + lines.join('\n') + '\n\n' +
    (cuts.length ? T.txtCuts + '\n' + cuts.map((c) => '- ' + c.task + ': ' + c.original + ' -> ' + c.adjusted + ' (' + c.reason + ')').join('\n') : '');
  downloadFile('my-schedule.txt', text, 'text/plain');
}
function downloadCalendar() {
  if (!state.scheduleResult) { alert(I18N.ui.noSchedule); return; }
  const now = new Date();
  const y = now.getFullYear(), m = now.getMonth(), d = now.getDate();
  const pad = (n) => String(n).padStart(2, '0');
  const toICS = (mins) => {
    const dayOffset = Math.floor(mins / 1440);
    const mm = ((mins % 1440) + 1440) % 1440;
    const dt = new Date(y, m, d + dayOffset, Math.floor(mm / 60), mm % 60, 0);
    return dt.getFullYear() + pad(dt.getMonth() + 1) + pad(dt.getDate()) + 'T' + pad(dt.getHours()) + pad(dt.getMinutes()) + '00';
  };
  const stamp = now.getUTCFullYear() + pad(now.getUTCMonth() + 1) + pad(now.getUTCDate()) + 'T' + pad(now.getUTCHours()) + pad(now.getUTCMinutes()) + pad(now.getUTCSeconds()) + 'Z';
  const esc = (s) => String(s).replace(/([,;])/g, '\\$1');
  let ics = 'BEGIN:VCALENDAR\r\nVERSION:2.0\r\nPRODID:-//AI Life Planner//TH\r\nCALSCALE:GREGORIAN\r\n';
  state.scheduleResult.blocks.forEach((b, i) => {
    ics += 'BEGIN:VEVENT\r\nUID:ai-life-planner-' + Date.now() + '-' + i + '@local\r\nDTSTAMP:' + stamp +
      '\r\nDTSTART:' + toICS(b.s) + '\r\nDTEND:' + toICS(b.e) + '\r\nSUMMARY:' + esc(b.activity) +
      '\r\nCATEGORIES:' + esc(b.category) + '\r\nEND:VEVENT\r\n';
  });
  ics += 'END:VCALENDAR\r\n';
  downloadFile('my-schedule.ics', ics, 'text/calendar');
}
